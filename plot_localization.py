#!/usr/bin/env python3
import sys
import os
import argparse
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.animation as animation


def load_log_file(filename):
    """
    Robustly read the logger CSV generated by localization.py.
    Returns headers list and numpy array of data rows.
    """
    if not os.path.exists(filename):
        return None, None

    with open(filename, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    if len(lines) < 2:
        return None, None

    # Parse headers
    headers = [h.strip() for h in lines[0].split(",") if h.strip()]

    # Parse numeric rows
    rows = []
    for line in lines[1:]:
        tokens = [t.strip() for t in line.split(",") if t.strip()]
        if not tokens:
            continue
        try:
            row = [float(t) for t in tokens]
            # Ensure row length matches header length to avoid partial write glitches
            if len(row) >= len(headers):
                rows.append(row[:len(headers)])
        except ValueError:
            continue

    if not rows:
        return None, None

    data = np.array(rows)
    return headers, data


def extract_columns(headers, data):
    """Extract standard localization columns by name or positional index."""
    header_map = {name.lower(): idx for idx, name in enumerate(headers)}

    def get_col(name, fallback_idx):
        if name.lower() in header_map:
            return data[:, header_map[name.lower()]]
        elif fallback_idx < data.shape[1]:
            return data[:, fallback_idx]
        return None

    imu_ax = get_col("imu_ax", 0)
    imu_ay = get_col("imu_ay", 1)
    kf_ax = get_col("kf_ax", 2)
    kf_ay = get_col("kf_ay", 3)
    kf_vx = get_col("kf_vx", 4)
    kf_w = get_col("kf_w", 5)
    kf_x = get_col("kf_x", 6)
    kf_y = get_col("kf_y", 7)
    odom_x = data[:, header_map["odom_x"]] if "odom_x" in header_map else None
    odom_y = data[:, header_map["odom_y"]] if "odom_y" in header_map else None
    stamp = get_col("stamp", -1)

    if stamp is not None and len(stamp) > 1:
        t_raw = stamp - stamp[0]
        if t_raw[-1] > 1e6:
            t = t_raw * 1e-9
        else:
            t = t_raw
    else:
        t = np.arange(len(data))

    return {
        "t": t,
        "imu_ax": imu_ax,
        "imu_ay": imu_ay,
        "kf_ax": kf_ax,
        "kf_ay": kf_ay,
        "kf_vx": kf_vx,
        "kf_w": kf_w,
        "kf_x": kf_x,
        "kf_y": kf_y,
        "odom_x": odom_x,
        "odom_y": odom_y,
    }


def plot_localization_data(filename, save_path=None, title_prefix="", show_plot=True):
    headers, data = load_log_file(filename)
    if data is None:
        print(f"Error: No valid data found in {filename}", file=sys.stderr)
        return

    cols = extract_columns(headers, data)
    t = cols["t"]

    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    fig.suptitle(
        f"{title_prefix + ' - ' if title_prefix else ''}EKF Localization Performance ({filename})",
        fontsize=15,
        fontweight="bold",
    )

    # Subplot 1: Linear Acceleration X
    ax1 = axes[0, 0]
    if cols["imu_ax"] is not None:
        ax1.plot(t, cols["imu_ax"], label="IMU Measured $a_x$", color="tab:blue", alpha=0.55, linewidth=1.0)
    if cols["kf_ax"] is not None:
        ax1.plot(t, cols["kf_ax"], label="EKF Estimated $a_x$ ($\dot{v}$)", color="tab:orange", linewidth=2.0)
    ax1.set_title("Forward Acceleration $a_x$: Measured vs. EKF", fontweight="semibold")
    ax1.set_xlabel("Time [s]")
    ax1.set_ylabel("Acceleration [$m/s^2$]")
    ax1.grid(True, linestyle="--", alpha=0.7)
    ax1.legend(loc="upper right")

    # Subplot 2: Lateral Acceleration Y
    ax2 = axes[0, 1]
    if cols["imu_ay"] is not None:
        ax2.plot(t, cols["imu_ay"], label="IMU Measured $a_y$", color="tab:blue", alpha=0.55, linewidth=1.0)
    if cols["kf_ay"] is not None:
        ax2.plot(t, cols["kf_ay"], label="EKF Estimated $a_y$ ($v \cdot \omega$)", color="tab:green", linewidth=2.0)
    ax2.set_title("Lateral Acceleration $a_y$: Measured vs. EKF", fontweight="semibold")
    ax2.set_xlabel("Time [s]")
    ax2.set_ylabel("Acceleration [$m/s^2$]")
    ax2.grid(True, linestyle="--", alpha=0.7)
    ax2.legend(loc="upper right")

    # Subplot 3: Velocities
    ax3 = axes[1, 0]
    if cols["kf_vx"] is not None:
        ax3.plot(t, cols["kf_vx"], label="Linear Velocity $v$ [m/s]", color="tab:purple", linewidth=2.0)
    if cols["kf_w"] is not None:
        ax3.plot(t, cols["kf_w"], label="Angular Velocity $\omega$ [rad/s]", color="tab:red", linestyle="--", linewidth=2.0)
    ax3.set_title("EKF Estimated Velocities", fontweight="semibold")
    ax3.set_xlabel("Time [s]")
    ax3.set_ylabel("Velocity")
    ax3.grid(True, linestyle="--", alpha=0.7)
    ax3.legend(loc="upper right")

    # Subplot 4: Trajectory
    ax4 = axes[1, 1]
    if cols["odom_x"] is not None and cols["odom_y"] is not None:
        ax4.plot(cols["odom_x"], cols["odom_y"], label="Odometry Path", color="tab:gray", linestyle="--", linewidth=1.5)
    if cols["kf_x"] is not None and cols["kf_y"] is not None:
        ax4.plot(cols["kf_x"], cols["kf_y"], label="EKF Path", color="tab:cyan", linewidth=2.0)
        ax4.plot(cols["kf_x"][0], cols["kf_y"][0], "go", markersize=8, label="Start $(0,0)$")
        ax4.plot(cols["kf_x"][-1], cols["kf_y"][-1], "rx", markersize=10, markeredgewidth=2, label="End")
        ax4.axis("equal")
    ax4.set_title("Robot Trajectory ($x$ vs. $y$)", fontweight="semibold")
    ax4.set_xlabel("X Position [m]")
    ax4.set_ylabel("Y Position [m]")
    ax4.grid(True, linestyle="--", alpha=0.7)
    ax4.legend(loc="best")

    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300)
        print(f"Plot saved successfully to: {save_path}")

    if show_plot:
        plt.show()
    else:
        plt.close()


def plot_localization_live(filename, interval=150, title_prefix="", save_path=None):
    """
    Live real-time updating plot that reads robotPose.csv as decisions.py runs.
    """
    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    title_text = f"{title_prefix + ' - ' if title_prefix else ''}LIVE EKF Localization ({filename})"
    fig.suptitle(title_text, fontsize=15, fontweight="bold")

    ax1, ax2 = axes[0, 0], axes[0, 1]
    ax3, ax4 = axes[1, 0], axes[1, 1]

    # Initialize line objects
    (line_imu_ax,) = ax1.plot([], [], label="IMU $a_x$", color="tab:blue", alpha=0.55, linewidth=1.0)
    (line_kf_ax,) = ax1.plot([], [], label="EKF $a_x$", color="tab:orange", linewidth=2.0)
    ax1.set_title("Forward Acceleration $a_x$", fontweight="semibold")
    ax1.set_xlabel("Time [s]")
    ax1.set_ylabel("[$m/s^2$]")
    ax1.grid(True, linestyle="--", alpha=0.7)
    ax1.legend(loc="upper right")

    (line_imu_ay,) = ax2.plot([], [], label="IMU $a_y$", color="tab:blue", alpha=0.55, linewidth=1.0)
    (line_kf_ay,) = ax2.plot([], [], label="EKF $a_y$ ($v \cdot \omega$)", color="tab:green", linewidth=2.0)
    ax2.set_title("Lateral Acceleration $a_y$", fontweight="semibold")
    ax2.set_xlabel("Time [s]")
    ax2.set_ylabel("[$m/s^2$]")
    ax2.grid(True, linestyle="--", alpha=0.7)
    ax2.legend(loc="upper right")

    (line_kf_vx,) = ax3.plot([], [], label="Velocity $v$ [m/s]", color="tab:purple", linewidth=2.0)
    (line_kf_w,) = ax3.plot([], [], label="Angular rate $\omega$ [rad/s]", color="tab:red", linestyle="--", linewidth=2.0)
    ax3.set_title("Estimated Velocities", fontweight="semibold")
    ax3.set_xlabel("Time [s]")
    ax3.set_ylabel("Velocity")
    ax3.grid(True, linestyle="--", alpha=0.7)
    ax3.legend(loc="upper right")

    (line_odom,) = ax4.plot([], [], label="Odometry", color="tab:gray", linestyle="--", linewidth=1.5)
    (line_traj,) = ax4.plot([], [], label="EKF Path", color="tab:cyan", linewidth=2.0)
    (point_start,) = ax4.plot([], [], "go", markersize=8, label="Start")
    (point_curr,) = ax4.plot([], [], "ro", markersize=8, label="Current Position")
    ax4.set_title("Robot Trajectory ($x$ vs $y$)", fontweight="semibold")
    ax4.set_xlabel("X [m]")
    ax4.set_ylabel("Y [m]")
    ax4.grid(True, linestyle="--", alpha=0.7)
    ax4.legend(loc="best")

    plt.tight_layout()

    def update(_frame):
        headers, data = load_log_file(filename)
        if data is None or len(data) < 2:
            return

        cols = extract_columns(headers, data)
        t = cols["t"]

        # Subplot 1
        if cols["imu_ax"] is not None:
            line_imu_ax.set_data(t, cols["imu_ax"])
        if cols["kf_ax"] is not None:
            line_kf_ax.set_data(t, cols["kf_ax"])
        ax1.relim()
        ax1.autoscale_view()

        # Subplot 2
        if cols["imu_ay"] is not None:
            line_imu_ay.set_data(t, cols["imu_ay"])
        if cols["kf_ay"] is not None:
            line_kf_ay.set_data(t, cols["kf_ay"])
        ax2.relim()
        ax2.autoscale_view()

        # Subplot 3
        if cols["kf_vx"] is not None:
            line_kf_vx.set_data(t, cols["kf_vx"])
        if cols["kf_w"] is not None:
            line_kf_w.set_data(t, cols["kf_w"])
        ax3.relim()
        ax3.autoscale_view()

        # Subplot 4
        if cols["odom_x"] is not None and cols["odom_y"] is not None:
            line_odom.set_data(cols["odom_x"], cols["odom_y"])
        if cols["kf_x"] is not None and cols["kf_y"] is not None:
            kx, ky = cols["kf_x"], cols["kf_y"]
            line_traj.set_data(kx, ky)
            point_start.set_data([kx[0]], [ky[0]])
            point_curr.set_data([kx[-1]], [ky[-1]])
            ax4.relim()
            ax4.autoscale_view()
            ax4.axis("equal")

            # Update live header with current coordinates
            curr_v = cols["kf_vx"][-1] if cols["kf_vx"] is not None else 0.0
            curr_w = cols["kf_w"][-1] if cols["kf_w"] is not None else 0.0
            fig.suptitle(
                f"{title_text} | t={t[-1]:.1f}s | Pos=({kx[-1]:.2f}, {ky[-1]:.2f}) | v={curr_v:.2f} m/s | w={curr_w:.2f} rad/s",
                fontsize=13,
                fontweight="bold",
            )

    ani = animation.FuncAnimation(fig, update, interval=interval, cache_frame_data=False)
    plt.show()

    if save_path:
        fig.savefig(save_path, dpi=300)
        print(f"Final live plot saved successfully to: {save_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Plot EKF measurements vs estimates from robotPose.csv (MTE544 Lab 3)"
    )
    parser.add_argument(
        "--file",
        "-f",
        default="robotPose.csv",
        help="Path to the logged CSV file (default: robotPose.csv)",
    )
    parser.add_argument(
        "--live",
        "-l",
        action="store_true",
        help="Enable live updating plot while decisions.py runs",
    )
    parser.add_argument(
        "--interval",
        "-i",
        type=int,
        default=150,
        help="Update interval in milliseconds for live mode (default: 150ms)",
    )
    parser.add_argument(
        "--save",
        "-s",
        default=None,
        help="Optional path to save output image (e.g., ekf_results.png)",
    )
    parser.add_argument(
        "--title",
        "-t",
        default="",
        help="Optional title prefix to describe parameters (e.g., 'Q=0.5, R=0.5')",
    )

    args = parser.parse_args()

    if args.live:
        plot_localization_live(args.file, interval=args.interval, title_prefix=args.title, save_path=args.save)
    else:
        show = args.save is None
        plot_localization_data(args.file, save_path=args.save, title_prefix=args.title, show_plot=show)
